from datetime import datetime
def get_current_time(format_type:str="datetime") -> str:
    """获取当前日期或者时间。formate_type可选：=:'date'、'time'、'datetime'"""
    now = datetime.now()
    if format_type == "date":
        return f"当前日期:{now.strftime('%Y-%m-%d')}"
    elif format_type == "time":
        return f"当前时间:{now.strftime('%H:%M:%S')}"
    return f"当前诶器时间：{now.strftime('%Y-%m-%d %H:%M:%S')}"



































































































